-- 01. MULTI-TABLE JOIN (INNER JOIN + LEFT JOIN)
-- Shows each fuel sale, employee, and optional customer.
SELECT
    s.sale_id,
    s.sale_datetime,
    e.name AS employee_name,
    NVL(c.name, 'Walk-in Customer') AS customer_name,
    ft.fuel_name,
    fs.tank_name,
    s.liters_sold,
    s.payment_method,
    s.total_amount
FROM sale s
JOIN employee e
    ON e.employee_id = s.employee_id
LEFT JOIN customer c
    ON c.customer_id = s.customer_id
JOIN fuel_stock fs
    ON fs.fuel_stock_id = s.fuel_stock_id
JOIN fuel_type ft
    ON ft.fuel_type_id = fs.fuel_type_id
ORDER BY s.sale_datetime DESC, s.sale_id DESC;


-- 02. GROUP BY + HAVING + JOINS
-- Fuel types with at least two sales, grouped by revenue.
SELECT
    ft.fuel_name AS fuel_type,
    COUNT(s.sale_id) AS transaction_count,
    SUM(s.liters_sold) AS total_liters_sold,
    SUM(s.total_amount) AS total_revenue
FROM sale s
JOIN fuel_stock fs
    ON s.fuel_stock_id = fs.fuel_stock_id
JOIN fuel_type ft
    ON fs.fuel_type_id = ft.fuel_type_id
GROUP BY ft.fuel_name
HAVING COUNT(s.sale_id) >= 2
ORDER BY total_revenue DESC;


-- 03. SUBQUERY #1: SCALAR SUBQUERY
-- Products priced above the average product price.
SELECT
    pi.product_id,
    pi.product_name,
    pi.selling_price,
    pi.stock_quantity
FROM product_item pi
WHERE pi.selling_price > (
    SELECT AVG(selling_price)
    FROM product_item
)
ORDER BY pi.selling_price DESC;


-- 04. SUBQUERY #2: CORRELATED SUBQUERIES (SUM + EXISTS)
-- Products sold and their total quantities.
SELECT
    pi.product_id,
    pi.product_name,
    pi.selling_price,
    (
        SELECT SUM(sp.quantity)
        FROM sale_product sp
        WHERE sp.product_id = pi.product_id
    ) AS total_units_sold
FROM product_item pi
WHERE EXISTS (
    SELECT 1
    FROM sale_product sp
    WHERE sp.product_id = pi.product_id
)
ORDER BY total_units_sold DESC, pi.product_id;


-- 05. SUBQUERY IN FROM + UNION ALL + CONDITIONAL AGGREGATION
-- Daily fuel, product, and combined revenue; avoid double-counting order headers.
SELECT
    sale_date,
    SUM(CASE WHEN sale_source = 'FUEL'
             THEN revenue ELSE 0 END) AS fuel_revenue,
    SUM(CASE WHEN sale_source = 'PRODUCT'
             THEN revenue ELSE 0 END) AS product_revenue,
    SUM(revenue) AS combined_revenue
FROM (
    SELECT
        TRUNC(sale_datetime) AS sale_date,
        'FUEL' AS sale_source,
        total_amount AS revenue
    FROM sale
    UNION ALL
    SELECT
        TRUNC(sale_datetime) AS sale_date,
        'PRODUCT' AS sale_source,
        total_amount AS revenue
    FROM sale_product
)
GROUP BY sale_date
ORDER BY sale_date;


-- 06. TOP-N QUERY: INLINE ORDER BY FOLLOWED BY ROWNUM
-- Five highest-value fuel sales using an inline query and ROWNUM.
SELECT
    ranked.sale_id,
    ranked.fuel_name,
    ranked.employee_name,
    ranked.total_amount
FROM (
    SELECT
        s.sale_id,
        ft.fuel_name,
        e.name AS employee_name,
        s.total_amount
    FROM sale s
    JOIN fuel_stock fs
        ON fs.fuel_stock_id = s.fuel_stock_id
    JOIN fuel_type ft
        ON ft.fuel_type_id = fs.fuel_type_id
    JOIN employee e
        ON e.employee_id = s.employee_id
    ORDER BY s.total_amount DESC, s.sale_id ASC
) ranked
WHERE ROWNUM <= 5;


-- 07. ADVANCED AGGREGATION: ROLLUP + GROUPING()
-- Revenue subtotals and totals by fuel and payment method.
SELECT
    CASE
        WHEN GROUPING(ft.fuel_name) = 1
        THEN 'ALL FUEL TYPES'
        ELSE ft.fuel_name
    END AS fuel_type,
    CASE
        WHEN GROUPING(s.payment_method) = 1
        THEN 'ALL PAYMENT METHODS'
        ELSE s.payment_method
    END AS payment_method,
    COUNT(*) AS transaction_count,
    SUM(s.total_amount) AS total_revenue
FROM sale s
JOIN fuel_stock fs
    ON s.fuel_stock_id = fs.fuel_stock_id
JOIN fuel_type ft
    ON fs.fuel_type_id = ft.fuel_type_id
GROUP BY ROLLUP (
    ft.fuel_name,
    s.payment_method
)
ORDER BY
    GROUPING(ft.fuel_name),
    ft.fuel_name,
    GROUPING(s.payment_method),
    s.payment_method;


-- 08. PRODUCT CATEGORY REPORT WITH JOIN + GROUP BY + HAVING
-- Categories with product sales above THB 100.
SELECT
