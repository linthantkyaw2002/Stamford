-- Check database-role privileges.
SELECT
    SYS_CONTEXT('USERENV', 'SESSION_USER') AS database_session_user,
    SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA') AS current_schema,
    CASE WHEN EXISTS
        (SELECT 1 FROM session_privs WHERE privilege = 'CREATE ROLE')
        THEN 'YES' ELSE 'NO' END AS can_create_db_role,
    CASE WHEN EXISTS
        (SELECT 1 FROM session_privs WHERE privilege = 'GRANT ANY ROLE')
        THEN 'YES' ELSE 'NO' END AS can_grant_any_role
FROM dual;


