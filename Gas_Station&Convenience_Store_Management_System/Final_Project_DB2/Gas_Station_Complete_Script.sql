            RAISE_APPLICATION_ERROR(-20120, 'Unexpected grant target');
        END IF;

        SELECT COUNT(*) INTO l_existing
        FROM user_tab_privs_made
        WHERE table_name = 'V_PRODUCT_SALES_SUMMARY'
          AND grantee = p_grantee
          AND privilege = 'SELECT';

        IF l_existing > 0 THEN
            DBMS_OUTPUT.PUT_LINE('EXISTS: SELECT on summary for ' || p_grantee);
            RETURN;
        END IF;

        IF p_grantee = 'MANAGER' THEN
            SELECT COUNT(*) INTO l_user_exists
            FROM all_users
            WHERE username = 'MANAGER';
            IF l_user_exists = 0 THEN
                DBMS_OUTPUT.PUT_LINE(
                    'NOT APPLIED: database user MANAGER not present');
                RETURN;
            END IF;
        END IF;

        BEGIN
            EXECUTE IMMEDIATE
                'GRANT SELECT ON V_PRODUCT_SALES_SUMMARY TO ' || p_grantee;
            DBMS_OUTPUT.PUT_LINE('GRANTED: SELECT on summary to ' || p_grantee);
        EXCEPTION
            WHEN OTHERS THEN
                IF SQLCODE = -1031 THEN
                    DBMS_OUTPUT.PUT_LINE(
                        'NOT APPLIED: insufficient privileges for ' || p_grantee);
                ELSE
                    RAISE;
                END IF;
        END;
    END;
BEGIN
    ensure_summary_select('PUBLIC');
    ensure_summary_select('MANAGER');
END;
