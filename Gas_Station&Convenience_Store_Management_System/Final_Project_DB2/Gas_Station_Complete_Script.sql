  CREATE OR REPLACE FORCE EDITIONABLE VIEW "V_FUEL_SALES_DETAILS" ("SALE_ID", "SALE_DATETIME", "EMPLOYEE_NAME", "CUSTOMER_NAME", "FUEL_NAME", "TANK_NAME", "LITERS_SOLD", "PRICE_PER_LITER", "TOTAL_AMOUNT", "PAYMENT_METHOD") AS 
  SELECT
    s.sale_id,
    s.sale_datetime,
    e.name AS employee_name,
    c.name AS customer_name,
    ft.fuel_name,
    fs.tank_name,
    s.liters_sold,
    ft.price_per_liter,
    s.total_amount,
    s.payment_method
FROM SALE s
JOIN EMPLOYEE e
    ON s.employee_id = e.employee_id
LEFT JOIN CUSTOMER c
    ON s.customer_id = c.customer_id
JOIN FUEL_STOCK fs
    ON s.fuel_stock_id = fs.fuel_stock_id
JOIN FUEL_TYPE ft
    ON fs.fuel_type_id = ft.fuel_type_id;

  CREATE OR REPLACE FORCE EDITIONABLE VIEW "V_PRODUCT_SALES_DETAILS" ("SALE_PRODUCT_ID", "SALE_DATETIME", "PRODUCT_NAME", "CATEGORY_NAME", "EMPLOYEE_NAME", "CUSTOMER_NAME", "QUANTITY", "TOTAL_AMOUNT") AS 
  SELECT
    sp.sale_product_id,
    sp.sale_datetime,
    pi.product_name,
    pc.category_name,
    e.name AS employee_name,
    c.name AS customer_name,
    sp.quantity,
    sp.total_amount
FROM SALE_PRODUCT sp
JOIN PRODUCT_ITEM pi
    ON sp.product_id = pi.product_id
JOIN PRODUCT_CATEGORY pc
    ON pi.category_id = pc.category_id
JOIN EMPLOYEE e
    ON sp.employee_id = e.employee_id
LEFT JOIN CUSTOMER c
    ON sp.customer_id = c.customer_id;

  CREATE OR REPLACE FORCE EDITIONABLE VIEW "V_PRODUCT_SALES_SUMMARY" ("CATEGORY_NAME", "PRODUCT_NAME", "TOTAL_QUANTITY_SOLD", "TOTAL_SALES_AMOUNT") AS 
  SELECT
    pc.category_name,
    pi.product_name,
    SUM(sp.quantity) AS total_quantity_sold,
    SUM(sp.total_amount) AS total_sales_amount
FROM SALE_PRODUCT sp
JOIN PRODUCT_ITEM pi
    ON sp.product_id = pi.product_id
JOIN PRODUCT_CATEGORY pc
    ON pi.category_id = pc.category_id
GROUP BY
    pc.category_name,
    pi.product_name;

  CREATE OR REPLACE FORCE EDITIONABLE VIEW "V_TOP_FUEL_SALES" ("SALE_ID", "EMPLOYEE_NAME", "CUSTOMER_NAME", "FUEL_NAME", "LITERS_SOLD", "TOTAL_AMOUNT") AS 
  SELECT
    sale_id,
    employee_name,
    customer_name,
    fuel_name,
    liters_sold,
    total_amount
FROM (
    SELECT
        s.sale_id,
        e.name AS employee_name,
        c.name AS customer_name,
        ft.fuel_name,
        s.liters_sold,
        s.total_amount
    FROM SALE s
    JOIN EMPLOYEE e
        ON s.employee_id = e.employee_id
    LEFT JOIN CUSTOMER c
        ON s.customer_id = c.customer_id
    JOIN FUEL_STOCK fs
        ON s.fuel_stock_id = fs.fuel_stock_id
    JOIN FUEL_TYPE ft
        ON fs.fuel_type_id = ft.fuel_type_id
    ORDER BY s.total_amount DESC
)
WHERE ROWNUM <= 5;



